#!/usr/bin/env bash
# Sourced by scripts/deploy.sh on the local control plane.
# Callable without SSH. Sources common.sh for die.

set -euo pipefail

_load_runtime_env_common() {
  local dir
  dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  # shellcheck source=common.sh
  source "$dir/common.sh"
}
_load_runtime_env_common
unset -f _load_runtime_env_common

# Refuse localhost unless ALLOW_LOCAL_TARGET=1. Same hosts and error text as before.
refuse_local_target() {
  if [[ "$TARGET_HOST" == "localhost" || "$TARGET_HOST" == "127.0.0.1" || "$TARGET_HOST" == "::1" ]]; then
    if [[ "${ALLOW_LOCAL_TARGET:-}" != "1" ]]; then
      die "refusing TARGET_HOST=$TARGET_HOST (set ALLOW_LOCAL_TARGET=1 to override)"
    fi
  fi
}

# Filtered Hermes runtime env. Writes to stdout. Does not SSH.
build_runtime_env() {
  echo "# Generated by scripts/deploy.sh — Hermes runtime secrets only"
  echo "OPENROUTER_API_KEY=${OPENROUTER_API_KEY}"
  echo "TELEGRAM_BOT_TOKEN=${TELEGRAM_BOT_TOKEN}"
  echo "TELEGRAM_ALLOWED_USERS=${TELEGRAM_ALLOWED_USERS}"
  [[ -n "${TELEGRAM_HOME_CHANNEL:-}" ]] && echo "TELEGRAM_HOME_CHANNEL=${TELEGRAM_HOME_CHANNEL}"
  [[ -n "${TELEGRAM_HOME_CHANNEL_NAME:-}" ]] && echo "TELEGRAM_HOME_CHANNEL_NAME=${TELEGRAM_HOME_CHANNEL_NAME}"
  [[ -n "${TELEGRAM_GROUP_ALLOWED_USERS:-}" ]] && echo "TELEGRAM_GROUP_ALLOWED_USERS=${TELEGRAM_GROUP_ALLOWED_USERS}"
  [[ -n "${TELEGRAM_GROUP_ALLOWED_CHATS:-}" ]] && echo "TELEGRAM_GROUP_ALLOWED_CHATS=${TELEGRAM_GROUP_ALLOWED_CHATS}"
  # Discord gateway (optional — both token + allowlist required to enable)
  if [[ -n "${DISCORD_BOT_TOKEN:-}" && -n "${DISCORD_ALLOWED_USERS:-}" ]]; then
    echo "DISCORD_BOT_TOKEN=${DISCORD_BOT_TOKEN}"
    echo "DISCORD_ALLOWED_USERS=${DISCORD_ALLOWED_USERS}"
    [[ -n "${DISCORD_HOME_CHANNEL:-}" ]] && echo "DISCORD_HOME_CHANNEL=${DISCORD_HOME_CHANNEL}"
    [[ -n "${DISCORD_HOME_CHANNEL_NAME:-}" ]] && echo "DISCORD_HOME_CHANNEL_NAME=${DISCORD_HOME_CHANNEL_NAME}"
    [[ -n "${DISCORD_FREE_RESPONSE_CHANNELS:-}" ]] && echo "DISCORD_FREE_RESPONSE_CHANNELS=${DISCORD_FREE_RESPONSE_CHANNELS}"
    [[ -n "${DISCORD_ALLOWED_CHANNELS:-}" ]] && echo "DISCORD_ALLOWED_CHANNELS=${DISCORD_ALLOWED_CHANNELS}"
    [[ -n "${DISCORD_IGNORED_CHANNELS:-}" ]] && echo "DISCORD_IGNORED_CHANNELS=${DISCORD_IGNORED_CHANNELS}"
    [[ -n "${DISCORD_NO_THREAD_CHANNELS:-}" ]] && echo "DISCORD_NO_THREAD_CHANNELS=${DISCORD_NO_THREAD_CHANNELS}"
    [[ -n "${DISCORD_REQUIRE_MENTION:-}" ]] && echo "DISCORD_REQUIRE_MENTION=${DISCORD_REQUIRE_MENTION}"
    [[ -n "${DISCORD_THREAD_REQUIRE_MENTION:-}" ]] && echo "DISCORD_THREAD_REQUIRE_MENTION=${DISCORD_THREAD_REQUIRE_MENTION}"
    [[ -n "${DISCORD_AUTO_THREAD:-}" ]] && echo "DISCORD_AUTO_THREAD=${DISCORD_AUTO_THREAD}"
    [[ -n "${DISCORD_IGNORE_NO_MENTION:-}" ]] && echo "DISCORD_IGNORE_NO_MENTION=${DISCORD_IGNORE_NO_MENTION}"
    [[ -n "${DISCORD_REACTIONS:-}" ]] && echo "DISCORD_REACTIONS=${DISCORD_REACTIONS}"
    [[ -n "${DISCORD_ALLOW_BOTS:-}" ]] && echo "DISCORD_ALLOW_BOTS=${DISCORD_ALLOW_BOTS}"
    [[ -n "${DISCORD_ALLOW_ALL_USERS:-}" ]] && echo "DISCORD_ALLOW_ALL_USERS=${DISCORD_ALLOW_ALL_USERS}"
  fi
  [[ -n "${GATEWAY_ALLOW_ALL_USERS:-}" ]] && echo "GATEWAY_ALLOW_ALL_USERS=${GATEWAY_ALLOW_ALL_USERS}"
  [[ -n "${FIRECRAWL_API_KEY:-}" ]] && echo "FIRECRAWL_API_KEY=${FIRECRAWL_API_KEY}"
  # Self-hosted web stack (./scripts/deploy.sh --firecrawl)
  echo "FIRECRAWL_API_URL=${FIRECRAWL_API_URL:-http://127.0.0.1:3002}"
  echo "SEARXNG_URL=${SEARXNG_URL:-http://127.0.0.1:8888}"
  [[ -n "${PARALLEL_API_KEY:-}" ]] && echo "PARALLEL_API_KEY=${PARALLEL_API_KEY}"
  [[ -n "${EXA_API_KEY:-}" ]] && echo "EXA_API_KEY=${EXA_API_KEY}"
  [[ -n "${VOICE_TOOLS_OPENAI_KEY:-}" ]] && echo "VOICE_TOOLS_OPENAI_KEY=${VOICE_TOOLS_OPENAI_KEY}"
  [[ -n "${GROQ_API_KEY:-}" ]] && echo "GROQ_API_KEY=${GROQ_API_KEY}"
  [[ -n "${ELEVENLABS_API_KEY:-}" ]] && echo "ELEVENLABS_API_KEY=${ELEVENLABS_API_KEY}"
  [[ -n "${GITHUB_TOKEN:-}" ]] && echo "GITHUB_TOKEN=${GITHUB_TOKEN}"
  # Prefer plain api.telegram.org (avoids slow DoH fallback-IP path on some VPS networks)
  echo "HERMES_TELEGRAM_DISABLE_FALLBACK_IPS=${HERMES_TELEGRAM_DISABLE_FALLBACK_IPS:-true}"
  # VPS system timezone (IANA). Applied on every deploy via set-timezone.sh
  echo "TIMEZONE=${TIMEZONE:-Asia/Dubai}"
  echo "TZ=${TIMEZONE:-Asia/Dubai}"
  # S3 snapshot (skills + cron). Not forwarded into the Docker sandbox.
  [[ -n "${AWS_ACCESS_KEY_ID:-}" ]] && echo "AWS_ACCESS_KEY_ID=${AWS_ACCESS_KEY_ID}"
  [[ -n "${AWS_SECRET_ACCESS_KEY:-}" ]] && echo "AWS_SECRET_ACCESS_KEY=${AWS_SECRET_ACCESS_KEY}"
  [[ -n "${AWS_DEFAULT_REGION:-}" ]] && echo "AWS_DEFAULT_REGION=${AWS_DEFAULT_REGION}"
  [[ -n "${S3_BUCKET:-}" ]] && echo "S3_BUCKET=${S3_BUCKET}"
  [[ -n "${S3_PREFIX:-}" ]] && echo "S3_PREFIX=${S3_PREFIX}"
  # Notion: only push when BOTH key and parent page id are set (never half-configure)
  if [[ -n "${NOTION_API_KEY:-}" && -n "${NOTION_REPORTS_PARENT_PAGE_ID:-}" ]]; then
    echo "NOTION_API_KEY=${NOTION_API_KEY}"
    echo "NOTION_TOKEN=${NOTION_TOKEN:-$NOTION_API_KEY}"
    echo "NOTION_REPORTS_PARENT_PAGE_ID=${NOTION_REPORTS_PARENT_PAGE_ID}"
    [[ -n "${NOTION_API_VERSION:-}" ]] && echo "NOTION_API_VERSION=${NOTION_API_VERSION}"
    [[ -n "${NOTION_FREELANCE_DB_ID:-}" ]] && echo "NOTION_FREELANCE_DB_ID=${NOTION_FREELANCE_DB_ID}"
    [[ -n "${NOTION_ROLE_TEMPLATE_PAGE_ID:-}" ]] && echo "NOTION_ROLE_TEMPLATE_PAGE_ID=${NOTION_ROLE_TEMPLATE_PAGE_ID}"
  fi
  # A trailing [[ ]] && echo returns 1. In a { } group that did not abort deploy; a function would.
  return 0
}

#!/usr/bin/env bash
# Runs ON the VPS. Wire Notion MCP + notion-reports skill for Hermes.
# Requires NOTION_API_KEY + NOTION_REPORTS_PARENT_PAGE_ID in ~/.hermes/.env
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
source "$SCRIPT_DIR/../lib/common.sh"

export PATH="${HOME}/.local/bin:/usr/local/bin:${PATH}"
HERMES_HOME="${HERMES_HOME:-$HOME/.hermes}"
ENV_FILE="$HERMES_HOME/.env"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
EXT_DIR="$ROOT/extensions/notion"
if [[ ! -d "$EXT_DIR/skill" ]]; then
  for cand in "$HOME/hermes-setup/extensions/notion"; do
    [[ -d "$cand/skill" ]] && EXT_DIR="$cand" && break
  done
fi
[[ -d "$EXT_DIR/skill" ]] || die "extensions/notion not found (sync repo first)"

command -v hermes >/dev/null 2>&1 || die "hermes not on PATH"

# Load Hermes env
if [[ -f "$ENV_FILE" ]]; then
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
fi

# Merge NOTION_* from payload remote.env (preferred source from Mac deploy)
PAYLOAD_ENV="${REMOTE_ENV:-$(cd "$SCRIPT_DIR/../.." && pwd)/remote.env}"
if [[ -f "$PAYLOAD_ENV" ]]; then
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ "$line" == NOTION_*=* ]] || continue
    key="${line%%=*}"
    val="${line#*=}"
    printf -v "$key" '%s' "$val"
    export "$key"
  done <"$PAYLOAD_ENV"
fi

KEY="${NOTION_API_KEY:-${NOTION_TOKEN:-}}"
PARENT="${NOTION_REPORTS_PARENT_PAGE_ID:-}"

# Flexible no-op: never half-configure Notion without both vars
if [[ -z "$KEY" || -z "$PARENT" ]]; then
  log "Skipping Notion setup — both required (missing one or both):"
  if [[ -n "$KEY" ]]; then log "  NOTION_API_KEY: set"; else log "  NOTION_API_KEY: unset"; fi
  if [[ -n "$PARENT" ]]; then log "  NOTION_REPORTS_PARENT_PAGE_ID: set"; else log "  NOTION_REPORTS_PARENT_PAGE_ID: unset"; fi
  log "No MCP/skill/config changes written."
  exit 0
fi

# Persist aliases into Hermes .env
upsert_env() {
  local key="$1" val="$2" f="$ENV_FILE"
  mkdir -p "$(dirname "$f")"
  touch "$f"
  chmod 600 "$f"
  python3 - "$f" "$key" "$val" <<'PY'
from pathlib import Path
import sys
path, key, val = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
lines = path.read_text().splitlines() if path.exists() else []
out, found = [], False
for line in lines:
    if line.startswith(key + "="):
        out.append(f"{key}={val}")
        found = True
    else:
        out.append(line)
if not found:
    if out and out[-1].strip():
        out.append("")
    out.append(f"{key}={val}")
path.write_text("\n".join(out) + "\n")
PY
}

upsert_env NOTION_API_KEY "$KEY"
upsert_env NOTION_TOKEN "$KEY"
upsert_env NOTION_REPORTS_PARENT_PAGE_ID "$PARENT"
[[ -n "${NOTION_API_VERSION:-}" ]] && upsert_env NOTION_API_VERSION "$NOTION_API_VERSION"

log "Ensuring Node.js / npx for Notion MCP"
if ! command -v npx >/dev/null 2>&1; then
  if command -v apt-get >/dev/null 2>&1; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq >/dev/null 2>&1 || true
    apt-get install -y -qq nodejs npm >/dev/null 2>&1 || true
  fi
fi
command -v npx >/dev/null 2>&1 || die "npx required for @notionhq/notion-mcp-server"

# Non-secret local config for the agent
mkdir -p "$HERMES_HOME/notion"
cat >"$HERMES_HOME/notion/config.env" <<EOF
# Generated by notion-up.sh — non-secret pointers (token stays in ~/.hermes/.env)
NOTION_REPORTS_PARENT_PAGE_ID=${PARENT}
EOF
chmod 644 "$HERMES_HOME/notion/config.env"

# Skill
SKILL_DST="$HERMES_HOME/skills/notion-reports"
log "Installing skill → $SKILL_DST"
mkdir -p "$SKILL_DST"
install -m 644 "$EXT_DIR/skill/SKILL.md" "$SKILL_DST/SKILL.md"

# Merge mcp_servers.notion into config.yaml without clobbering other servers
CFG="$HERMES_HOME/config.yaml"
[[ -f "$CFG" ]] || die "missing $CFG"
log "Merging mcp_servers.notion into config.yaml"

python3 - "$CFG" <<'PY'
from pathlib import Path
import re, sys

cfg = Path(sys.argv[1])
text = cfg.read_text()

# Remove previous notion server block if present under mcp_servers
# Strategy: ensure mcp_servers: exists, then set/replace notion: entry via line-based merge

notion_block = """  notion:
    command: "npx"
    args: ["-y", "@notionhq/notion-mcp-server"]
    env:
      NOTION_TOKEN: "${NOTION_TOKEN}"
    enabled: true
"""

if not re.search(r"(?m)^mcp_servers:\s*$", text):
    text = text.rstrip() + "\n\nmcp_servers:\n" + notion_block
else:
    # Extract mcp_servers section
    m = re.search(r"(?ms)^(mcp_servers:\n)(.*?)(?=^[a-zA-Z_]|\Z)", text)
    if not m:
        text = text.rstrip() + "\n\nmcp_servers:\n" + notion_block
    else:
        start, stop = m.start(), m.end()
        before, head, body, after = text[:start], m.group(1), m.group(2), text[stop:]
        # Drop existing notion: sub-block (indented under mcp_servers)
        body2 = re.sub(
            r"(?ms)^  notion:\n(?:    .*\n)*",
            "",
            body,
        )
        body2 = body2.rstrip() + "\n" + notion_block
        if not body2.endswith("\n"):
            body2 += "\n"
        text = before + head + body2 + after

cfg.write_text(text if text.endswith("\n") else text + "\n")
print(f"updated {cfg}")
PY

# skills.config parent id (non-secret)
python3 - "$CFG" "$PARENT" <<'PY'
from pathlib import Path
import re, sys
cfg, parent = Path(sys.argv[1]), sys.argv[2]
text = cfg.read_text()
# Ensure skills.config.notion_reports.parent_page_id
if not re.search(r"(?m)^skills:\s*$", text):
    text = text.rstrip() + "\n\nskills:\n  config:\n    notion_reports:\n      parent_page_id: \"%s\"\n" % parent
else:
    if "notion_reports" not in text:
        # insert under skills:
        text = re.sub(
            r"(?m)^(skills:\s*)$",
            r"\1\n  config:\n    notion_reports:\n      parent_page_id: \"%s\"" % parent,
            text,
            count=1,
        )
    elif re.search(r"(?m)^\s+parent_page_id:\s*", text):
        text = re.sub(
            r"(?m)^(\s+parent_page_id:\s*).*$",
            r'\1"%s"' % parent,
            text,
            count=1,
        )
    else:
        text = re.sub(
            r"(?m)^(  config:\s*)$",
            r"\1\n    notion_reports:\n      parent_page_id: \"%s\"" % parent,
            text,
            count=1,
        )
cfg.write_text(text if text.endswith("\n") else text + "\n")
print("skills.config.notion_reports.parent_page_id set")
PY

# API smoke (token + parent shared)
log "Verifying Notion API token + parent page access"
python3 - <<'PY'
import json, os, sys, urllib.error, urllib.request

token = os.environ.get("NOTION_TOKEN") or os.environ.get("NOTION_API_KEY")
parent = os.environ.get("NOTION_REPORTS_PARENT_PAGE_ID", "").replace("-", "")
if len(parent) == 32:
    parent = f"{parent[:8]}-{parent[8:12]}-{parent[12:16]}-{parent[16:20]}-{parent[20:]}"
ver = os.environ.get("NOTION_API_VERSION", "2022-06-28")
headers = {
    "Authorization": f"Bearer {token}",
    "Notion-Version": ver,
    "Content-Type": "application/json",
}

def get(url):
    req = urllib.request.Request(url, headers=headers, method="GET")
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)

try:
    me = get("https://api.notion.com/v1/users/me")
    print("token ok:", me.get("name") or me.get("id") or me.get("type"))
except urllib.error.HTTPError as e:
    print("token check FAILED:", e.code, e.read()[:300], file=sys.stderr)
    sys.exit(1)

try:
    page = get(f"https://api.notion.com/v1/pages/{parent}")
    print("parent page ok:", (page.get("url") or page.get("id"))[:80])
except urllib.error.HTTPError as e:
    body = e.read()[:400]
    print("parent page FAILED:", e.code, body, file=sys.stderr)
    print("Share the parent page with the integration (Connections).", file=sys.stderr)
    sys.exit(1)
PY

log "Restarting gateway (pick up MCP + env)"
hermes gateway restart 2>/dev/null || hermes gateway start 2>/dev/null || true
sleep 5
hermes gateway status 2>/dev/null || true

log "Notion ready"
log "  skill:  $SKILL_DST/SKILL.md"
log "  parent: $PARENT"
log "  mcp:    mcp_servers.notion → npx @notionhq/notion-mcp-server"
log "In Telegram: /new then ask to post a test report to Notion."

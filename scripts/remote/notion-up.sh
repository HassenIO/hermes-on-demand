#!/usr/bin/env bash
# Runs ON the VPS. Install Notion REST CLI + skill. Disables Notion MCP.
# Requires BOTH NOTION_API_KEY and NOTION_REPORTS_PARENT_PAGE_ID (else no-op).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
source "$SCRIPT_DIR/../lib/common.sh"

export PATH="${HOME}/.local/bin:/usr/local/bin:${PATH}"
HERMES_HOME="${HERMES_HOME:-$HOME/.hermes}"
ENV_FILE="$HERMES_HOME/.env"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
EXT_DIR="$ROOT/extensions/notion"
if [[ ! -d "$EXT_DIR/bin" ]]; then
  for cand in "$HOME/hermes-setup/extensions/notion"; do
    [[ -d "$cand/bin" ]] && EXT_DIR="$cand" && break
  done
fi
[[ -d "$EXT_DIR/bin" ]] || die "extensions/notion not found (sync repo first)"

command -v hermes >/dev/null 2>&1 || die "hermes not on PATH"

if [[ -f "$ENV_FILE" ]]; then
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
fi

PAYLOAD_ENV="${REMOTE_ENV:-$(cd "$SCRIPT_DIR/../.." && pwd)/remote.env}"
if [[ -f "$PAYLOAD_ENV" ]]; then
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ "$line" == NOTION_*=* ]] || continue
    key="${line%%=*}"
    val="${line#*=}"
    printf -v "$key" '%s' "$val"
    export "$key"
  done <"$PAYLOAD_ENV"
fi

KEY="${NOTION_API_KEY:-${NOTION_TOKEN:-}}"
PARENT="${NOTION_REPORTS_PARENT_PAGE_ID:-}"

if [[ -z "$KEY" || -z "$PARENT" ]]; then
  log "Skipping Notion setup — both required (missing one or both):"
  if [[ -n "$KEY" ]]; then log "  NOTION_API_KEY: set"; else log "  NOTION_API_KEY: unset"; fi
  if [[ -n "$PARENT" ]]; then log "  NOTION_REPORTS_PARENT_PAGE_ID: set"; else log "  NOTION_REPORTS_PARENT_PAGE_ID: unset"; fi
  log "No CLI/skill/config changes written."
  exit 0
fi

upsert_env() {
  local key="$1" val="$2" f="$ENV_FILE"
  mkdir -p "$(dirname "$f")"
  touch "$f"
  chmod 600 "$f"
  python3 - "$f" "$key" "$val" <<'PY'
from pathlib import Path
import sys
path, key, val = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
lines = path.read_text().splitlines() if path.exists() else []
out, found = [], False
for line in lines:
    if line.startswith(key + "="):
        out.append(f"{key}={val}")
        found = True
    else:
        out.append(line)
if not found:
    if out and out[-1].strip():
        out.append("")
    out.append(f"{key}={val}")
path.write_text("\n".join(out) + "\n")
PY
}

# Normalize parent id to dashed UUID when possible
PARENT_NORM="$(python3 -c "
import re,sys
s=sys.argv[1].replace('-','').strip()
print(f'{s[:8]}-{s[8:12]}-{s[12:16]}-{s[16:20]}-{s[20:]}' if len(s)==32 else sys.argv[1])
" "$PARENT")"

upsert_env NOTION_API_KEY "$KEY"
upsert_env NOTION_TOKEN "$KEY"
upsert_env NOTION_REPORTS_PARENT_PAGE_ID "$PARENT_NORM"
[[ -n "${NOTION_API_VERSION:-}" ]] && upsert_env NOTION_API_VERSION "$NOTION_API_VERSION"
export NOTION_API_KEY="$KEY" NOTION_TOKEN="$KEY" NOTION_REPORTS_PARENT_PAGE_ID="$PARENT_NORM"

# Install CLI
BIN_DIR="$HERMES_HOME/bin"
mkdir -p "$BIN_DIR" "${HOME}/.local/bin"
install -m 755 "$EXT_DIR/bin/notion_cli.py" "$BIN_DIR/notion_cli.py"
cat >"$BIN_DIR/notion-cli" <<EOF
#!/usr/bin/env bash
export HERMES_HOME="${HERMES_HOME}"
exec python3 "${BIN_DIR}/notion_cli.py" "\$@"
EOF
chmod 755 "$BIN_DIR/notion-cli"
ln -sfn "$BIN_DIR/notion-cli" "${HOME}/.local/bin/notion-cli"
# Host PATH (gateway / root shells)
if [[ -d /usr/local/bin ]] && [[ -w /usr/local/bin || "$(id -u)" -eq 0 ]]; then
  ln -sfn "$BIN_DIR/notion-cli" /usr/local/bin/notion-cli
  log "Installed $BIN_DIR/notion-cli → /usr/local/bin/notion-cli + ~/.local/bin"
else
  log "Installed $BIN_DIR/notion-cli → ~/.local/bin/notion-cli"
fi

# Skill
SKILL_DST="$HERMES_HOME/skills/notion-reports"
mkdir -p "$SKILL_DST"
install -m 644 "$EXT_DIR/skill/SKILL.md" "$SKILL_DST/SKILL.md"
log "Installed skill $SKILL_DST/SKILL.md"

mkdir -p "$HERMES_HOME/notion"
# Non-secret pointers (Job Hunt DB + template defaults from Hermes agent workflow)
FREELANCE_DB="${NOTION_FREELANCE_DB_ID:-xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx}"
ROLE_TMPL="${NOTION_ROLE_TEMPLATE_PAGE_ID:-xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx}"
cat >"$HERMES_HOME/notion/config.env" <<EOF
NOTION_REPORTS_PARENT_PAGE_ID=${PARENT_NORM}
NOTION_FREELANCE_DB_ID=${FREELANCE_DB}
NOTION_ROLE_TEMPLATE_PAGE_ID=${ROLE_TMPL}
EOF
chmod 644 "$HERMES_HOME/notion/config.env"
upsert_env NOTION_FREELANCE_DB_ID "$FREELANCE_DB"
upsert_env NOTION_ROLE_TEMPLATE_PAGE_ID "$ROLE_TMPL"
# Secrets for Docker sandbox (docker_forward_env is unreliable; CLI reads this file)
cat >"$HERMES_HOME/notion/env" <<EOF
# Generated by notion-up.sh — Notion-only secrets + IDs for sandbox CLI
NOTION_API_KEY=${KEY}
NOTION_TOKEN=${KEY}
NOTION_REPORTS_PARENT_PAGE_ID=${PARENT_NORM}
NOTION_FREELANCE_DB_ID=${FREELANCE_DB}
NOTION_ROLE_TEMPLATE_PAGE_ID=${ROLE_TMPL}
EOF
chmod 600 "$HERMES_HOME/notion/env"
log "Wrote $HERMES_HOME/notion/env (mode 600, Notion keys only)"

# Disable/remove Notion MCP so the model never hangs on mcp__notion__*
CFG="$HERMES_HOME/config.yaml"
if [[ -f "$CFG" ]]; then
  log "Disabling mcp_servers.notion (REST CLI only)"
  python3 - "$CFG" "$PARENT_NORM" <<'PY'
from pathlib import Path
import re, sys
cfg, parent = Path(sys.argv[1]), sys.argv[2]
text = cfg.read_text()

# Disable notion MCP block if present
def disable_notion_mcp(t: str) -> str:
    m = re.search(r"(?ms)^(mcp_servers:\n)(.*?)(?=^[a-zA-Z_]|\Z)", t)
    if not m:
        return t
    start, stop = m.start(), m.end()
    before, head, body, after = t[:start], m.group(1), m.group(2), t[stop:]
    # remove entire notion: sub-block
    body2 = re.sub(r"(?ms)^  notion:\n(?:    .*\n)*", "", body)
    # if mcp_servers empty of children, leave empty section or drop
    if not re.search(r"(?m)^  \w", body2):
        # drop empty mcp_servers
        return before + after
    if not body2.endswith("\n"):
        body2 += "\n"
    return before + head + body2 + after

text = disable_notion_mcp(text)

# skills.config.notion_reports
if not re.search(r"(?m)^skills:\s*$", text):
    text = text.rstrip() + (
        "\n\nskills:\n  config:\n    notion_reports:\n"
        f'      parent_page_id: "{parent}"\n'
        "      cli: notion-cli\n"
    )
else:
    if "notion_reports" not in text:
        text = re.sub(
            r"(?m)^(skills:\s*)$",
            r"\1\n  config:\n    notion_reports:\n"
            f'      parent_page_id: "{parent}"\n'
            "      cli: notion-cli",
            text,
            count=1,
        )
    else:
        if re.search(r"(?m)^\s+parent_page_id:\s*", text):
            text = re.sub(
                r"(?m)^(\s+parent_page_id:\s*).*$",
                rf'\1"{parent}"',
                text,
                count=1,
            )
        if "cli: notion-cli" not in text:
            text = re.sub(
                r"(?m)^(    notion_reports:\s*)$",
                r"\1\n      cli: notion-cli",
                text,
                count=1,
            )

cfg.write_text(text if text.endswith("\n") else text + "\n")
print(f"updated {cfg}")
PY
fi

# Ensure Docker sandbox can run bare `notion-cli` (PATH + mounts). Avoid YAML corruption.
if [[ -f "$CFG" ]]; then
  python3 - "$CFG" <<'PY'
from pathlib import Path
import os, re, sys

try:
    import yaml
except ImportError:
    # stdlib-only fallback: skip structured edit
    print("PyYAML missing — skip docker terminal patch")
    raise SystemExit(0)

cfg_path = Path(sys.argv[1])
data = yaml.safe_load(cfg_path.read_text()) or {}
term = data.setdefault("terminal", {})
home = os.environ.get("HERMES_HOME", str(Path.home() / ".hermes"))
bin_dir = f"{home}/bin"
notion_dir = f"{home}/notion"
docker_path = f"{bin_dir}:/usr/local/bin:/usr/local/sbin:/usr/sbin:/usr/bin:/sbin:/bin"

fwd = list(term.get("docker_forward_env") or [])
for k in ("GITHUB_TOKEN", "NOTION_API_KEY", "NOTION_TOKEN", "NOTION_REPORTS_PARENT_PAGE_ID"):
    if k not in fwd:
        fwd.append(k)
term["docker_forward_env"] = fwd

env = dict(term.get("docker_env") or {})
# drop any accidental list pollution under docker_env
env = {k: v for k, v in env.items() if isinstance(k, str) and not str(k).startswith("-")}
env["PATH"] = docker_path
term["docker_env"] = env

vols = []
seen = set()
for v in term.get("docker_volumes") or []:
    s = str(v).strip().strip('"')
    if s and s not in seen and not s.startswith("PATH:"):
        seen.add(s)
        vols.append(s)
wanted = [
    f"{home}/cache/documents:/output",
    f"{home}/memories:{home}/memories:ro",
    f"{home}/CV.md:{home}/CV.md:ro",
    f"{bin_dir}:{bin_dir}:ro",
    f"{notion_dir}:{notion_dir}:ro",
    # Login shells reset PATH — put CLI on default PATH inside the container
    f"{bin_dir}/notion-cli:/usr/local/bin/notion-cli:ro",
    "/root/.agent-reach:/root/.agent-reach",
]
for m in wanted:
    if m not in seen:
        host = m.split(":")[0]
        if Path(host).exists() or host.endswith("CV.md") or "agent-reach" in host:
            vols.append(m)
            seen.add(m)
term["docker_volumes"] = vols

# Preserve comments poorly — rewrite whole file cleanly from structure + keep other keys
text_out = yaml.safe_dump(data, default_flow_style=False, sort_keys=False, allow_unicode=True)
cfg_path.write_text(text_out)
print(f"patched terminal docker settings in {cfg_path}")
print("  PATH=", docker_path)
print("  volumes=", len(vols))
PY
fi

log "Smoke-testing notion-cli"
export PATH="$BIN_DIR:${HOME}/.local/bin:$PATH"
notion-cli me
notion-cli search "a" --limit 1 >/dev/null || warn "search smoke returned error (share pages with integration)"
notion-cli db-schema >/dev/null 2>&1 || warn "db-schema smoke failed (DB not shared?)"

log "Restarting gateway"
hermes gateway restart 2>/dev/null || hermes gateway start 2>/dev/null || true
sleep 4
hermes gateway status 2>/dev/null || true

# Drop old sandboxes so env/mounts apply
ids="$(docker ps -aq --filter label=hermes-agent=1 2>/dev/null || true)"
if [[ -n "${ids//[$'\n\r\t ']/}" ]]; then
  # shellcheck disable=SC2086
  docker rm -f $ids >/dev/null 2>&1 || true
fi

# notion-up may rewrite config.yaml — re-pin cron to current model
if [[ -f "$SCRIPT_DIR/pin-cron-models.sh" ]]; then
  bash "$SCRIPT_DIR/pin-cron-models.sh" || warn "cron model pin failed"
fi

log "Notion ready (REST CLI only — MCP disabled)"
log "  cli:    $(command -v notion-cli)"
log "  skill:  $SKILL_DST/SKILL.md"
log "  parent: $PARENT_NORM"
log "In Telegram: /new then: notion-cli search / find-db"

#!/usr/bin/env bash
# Mac control-plane entrypoint. Never installs Hermes on this machine.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib/common.sh
source "$ROOT/scripts/lib/common.sh"

MODE="full" # full | config-only | health | firecrawl
for arg in "$@"; do
  case "$arg" in
    --config-only) MODE="config-only" ;;
    --health) MODE="health" ;;
    --firecrawl) MODE="firecrawl" ;;
    -h|--help)
      cat <<'EOF'
Usage: ./scripts/deploy.sh [--config-only|--health|--firecrawl]

  (default)      Full remote bootstrap (packages, Docker, Hermes, gateway)
  --config-only  Push secrets + config.yaml and restart gateway
  --health       Remote healthcheck only
  --firecrawl    Deploy/start self-hosted Firecrawl and wire Hermes to it
EOF
      exit 0
      ;;
    *) die "unknown arg: $arg" ;;
  esac
done

ENV_FILE="$ROOT/.env"
load_dotenv "$ENV_FILE"

require_vars TARGET_HOST TARGET_USER OPENROUTER_API_KEY TELEGRAM_BOT_TOKEN TELEGRAM_ALLOWED_USERS

# Safety: do not install Hermes on the control machine by accident
if [[ "$TARGET_HOST" == "localhost" || "$TARGET_HOST" == "127.0.0.1" || "$TARGET_HOST" == "::1" ]]; then
  if [[ "${ALLOW_LOCAL_TARGET:-}" != "1" ]]; then
    die "refusing TARGET_HOST=$TARGET_HOST (set ALLOW_LOCAL_TARGET=1 to override)"
  fi
fi

SSH_PORT="${SSH_PORT:-22}"
REMOTE_DIR_RAW="${REMOTE_DIR:-~/hermes-setup}"
SSH_OPTS=(-o BatchMode=yes -o StrictHostKeyChecking=accept-new -p "$SSH_PORT")
if [[ -n "${SSH_IDENTITY_FILE:-}" ]]; then
  SSH_OPTS+=(-i "$SSH_IDENTITY_FILE")
fi

ssh_cmd() {
  ssh "${SSH_OPTS[@]}" "${TARGET_USER}@${TARGET_HOST}" "$@"
}

scp_cmd() {
  scp -P "$SSH_PORT" ${SSH_IDENTITY_FILE:+-i "$SSH_IDENTITY_FILE"} "$@"
}

log "SSH probe ${TARGET_USER}@${TARGET_HOST}:${SSH_PORT}"
ssh_cmd "true"

# Resolve remote dir on the server (expand ~ as remote user)
REMOTE_DIR="$(ssh_cmd "python3 - <<'PY'
import os
print(os.path.expanduser('${REMOTE_DIR_RAW}'))
PY
")"
log "Remote payload dir: $REMOTE_DIR"

# Build filtered runtime env (no deploy keys)
RUNTIME_ENV="$(mktemp)"
trap 'rm -f "$RUNTIME_ENV"' EXIT
{
  echo "# Generated by scripts/deploy.sh — Hermes runtime secrets only"
  echo "OPENROUTER_API_KEY=${OPENROUTER_API_KEY}"
  echo "TELEGRAM_BOT_TOKEN=${TELEGRAM_BOT_TOKEN}"
  echo "TELEGRAM_ALLOWED_USERS=${TELEGRAM_ALLOWED_USERS}"
  [[ -n "${TELEGRAM_HOME_CHANNEL:-}" ]] && echo "TELEGRAM_HOME_CHANNEL=${TELEGRAM_HOME_CHANNEL}"
  [[ -n "${TELEGRAM_HOME_CHANNEL_NAME:-}" ]] && echo "TELEGRAM_HOME_CHANNEL_NAME=${TELEGRAM_HOME_CHANNEL_NAME}"
  [[ -n "${TELEGRAM_GROUP_ALLOWED_USERS:-}" ]] && echo "TELEGRAM_GROUP_ALLOWED_USERS=${TELEGRAM_GROUP_ALLOWED_USERS}"
  [[ -n "${TELEGRAM_GROUP_ALLOWED_CHATS:-}" ]] && echo "TELEGRAM_GROUP_ALLOWED_CHATS=${TELEGRAM_GROUP_ALLOWED_CHATS}"
  [[ -n "${GATEWAY_ALLOW_ALL_USERS:-}" ]] && echo "GATEWAY_ALLOW_ALL_USERS=${GATEWAY_ALLOW_ALL_USERS}"
  [[ -n "${FIRECRAWL_API_KEY:-}" ]] && echo "FIRECRAWL_API_KEY=${FIRECRAWL_API_KEY}"
  # Self-hosted Firecrawl (default when using ./scripts/deploy.sh --firecrawl)
  echo "FIRECRAWL_API_URL=${FIRECRAWL_API_URL:-http://127.0.0.1:3002}"
  [[ -n "${PARALLEL_API_KEY:-}" ]] && echo "PARALLEL_API_KEY=${PARALLEL_API_KEY}"
  [[ -n "${EXA_API_KEY:-}" ]] && echo "EXA_API_KEY=${EXA_API_KEY}"
  [[ -n "${VOICE_TOOLS_OPENAI_KEY:-}" ]] && echo "VOICE_TOOLS_OPENAI_KEY=${VOICE_TOOLS_OPENAI_KEY}"
  [[ -n "${GROQ_API_KEY:-}" ]] && echo "GROQ_API_KEY=${GROQ_API_KEY}"
  [[ -n "${ELEVENLABS_API_KEY:-}" ]] && echo "ELEVENLABS_API_KEY=${ELEVENLABS_API_KEY}"
  [[ -n "${GITHUB_TOKEN:-}" ]] && echo "GITHUB_TOKEN=${GITHUB_TOKEN}"
  # Prefer plain api.telegram.org (avoids slow DoH fallback-IP path on some VPS networks)
  echo "HERMES_TELEGRAM_DISABLE_FALLBACK_IPS=${HERMES_TELEGRAM_DISABLE_FALLBACK_IPS:-true}"
} >"$RUNTIME_ENV"
chmod 600 "$RUNTIME_ENV"

if [[ "$MODE" == "health" ]]; then
  log "Remote healthcheck only"
  ssh_cmd "bash '$REMOTE_DIR/scripts/remote/healthcheck.sh'"
  exit 0
fi

log "Syncing payload to VPS"
ssh_cmd "mkdir -p '$REMOTE_DIR/scripts/lib' '$REMOTE_DIR/scripts/remote' '$REMOTE_DIR/config' '$REMOTE_DIR/firecrawl'"

# Prefer rsync if available both sides
if command -v rsync >/dev/null 2>&1 && ssh_cmd "command -v rsync >/dev/null 2>&1"; then
  RSYNC_SSH="ssh -p $SSH_PORT -o BatchMode=yes -o StrictHostKeyChecking=accept-new"
  [[ -n "${SSH_IDENTITY_FILE:-}" ]] && RSYNC_SSH+=" -i $SSH_IDENTITY_FILE"
  rsync -az -e "$RSYNC_SSH" \
    "$ROOT/scripts/lib/" "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/scripts/lib/"
  rsync -az -e "$RSYNC_SSH" \
    "$ROOT/scripts/remote/" "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/scripts/remote/"
  rsync -az -e "$RSYNC_SSH" \
    "$ROOT/config/" "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/config/"
  rsync -az -e "$RSYNC_SSH" \
    --exclude '.env' \
    "$ROOT/firecrawl/" "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/firecrawl/"
else
  scp_cmd -r "$ROOT/scripts/lib/"* "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/scripts/lib/"
  scp_cmd -r "$ROOT/scripts/remote/"* "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/scripts/remote/"
  scp_cmd -r "$ROOT/config/"* "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/config/"
  scp_cmd "$ROOT/firecrawl/docker-compose.yml" "$ROOT/firecrawl/.env.example" \
    "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/firecrawl/"
  ssh_cmd "mkdir -p '$REMOTE_DIR/firecrawl/lite'"
  scp_cmd "$ROOT/firecrawl/lite/"* \
    "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/firecrawl/lite/"
fi

scp_cmd "$RUNTIME_ENV" "${TARGET_USER}@${TARGET_HOST}:${REMOTE_DIR}/remote.env"
ssh_cmd "chmod 600 '$REMOTE_DIR/remote.env' && chmod +x '$REMOTE_DIR/scripts/remote/'*.sh 2>/dev/null || true"

if [[ "$MODE" == "firecrawl" ]]; then
  log "Deploying self-hosted Firecrawl + wiring Hermes (mode=${FIRECRAWL_MODE:-lite})"
  ssh_cmd "FIRECRAWL_MODE='${FIRECRAWL_MODE:-lite}' bash '$REMOTE_DIR/scripts/remote/firecrawl-up.sh'"
  log "Firecrawl deploy done. Ask the bot to scrape a URL."
  exit 0
fi

if [[ "$MODE" == "config-only" ]]; then
  log "Config-only: write Hermes home + restart gateway"
  ssh_cmd "bash -s" <<EOF
set -euo pipefail
export PATH="\$HOME/.local/bin:/usr/local/bin:\$PATH"
HERMES_HOME="\${HERMES_HOME:-\$HOME/.hermes}"
mkdir -p "\$HERMES_HOME"
install -m 600 '$REMOTE_DIR/remote.env' "\$HERMES_HOME/.env"
install -m 644 '$REMOTE_DIR/config/config.yaml.example' "\$HERMES_HOME/config.yaml"
hermes gateway restart 2>/dev/null || hermes gateway start
hermes gateway status || true
EOF
  ssh_cmd "bash '$REMOTE_DIR/scripts/remote/healthcheck.sh'"
  log "Config deploy done. Message your Telegram bot."
  exit 0
fi

log "Full remote bootstrap (this may take several minutes)"
ssh_cmd "bash '$REMOTE_DIR/scripts/remote/bootstrap.sh'"
ssh_cmd "bash '$REMOTE_DIR/scripts/remote/healthcheck.sh'"

log "Deploy complete. Open Telegram and message your bot."

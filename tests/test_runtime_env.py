"""Runtime env filter. Calls build_runtime_env, the function deploy.sh calls."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/deploy.sh — Hermes runtime secrets only"
REQUIRED = {
    "OPENROUTER_API_KEY": "test-openrouter",
    "TELEGRAM_BOT_TOKEN": "test-telegram",
    "TELEGRAM_ALLOWED_USERS": "1",
}
DEPLOY_ONLY = {
    "TARGET_HOST": "example.vps",
    "TARGET_USER": "ubuntu",
    "SSH_PORT": "22",
    "SSH_IDENTITY_FILE": "/tmp/id",
    "REMOTE_DIR": "~/hermes-setup",
    "ALLOW_LOCAL_TARGET": "1",
    "SKIP_FIRECRAWL": "1",
    "SKIP_MNEMOSYNE": "1",
    "SKIP_AGENT_REACH": "1",
    "PIN_CRON_FORCE": "1",
    "FIRECRAWL_MODE": "full",
    "LLM_MODEL": "should-not-forward",
}
ABSENT_EXACT = (
    "REMOTE_DIR",
    "ALLOW_LOCAL_TARGET",
    "PIN_CRON_FORCE",
    "FIRECRAWL_MODE",
    "LLM_MODEL",
)


def run_filter(extra: dict[str, str]) -> tuple[str, dict[str, str]]:
    script = f"""
set -euo pipefail
source "{ROOT}/scripts/lib/runtime-env.sh"
build_runtime_env
"""
    env = {
        "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
        "HOME": os.environ.get("HOME", "/tmp"),
    }
    env.update(extra)
    result = subprocess.run(
        ["bash", "-c", script],
        cwd=ROOT,
        env=env,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    parsed: dict[str, str] = {}
    for line in result.stdout.splitlines():
        if not line or line.startswith("#"):
            continue
        key, value = line.split("=", 1)
        parsed[key] = value
    return result.stdout, parsed


def assert_deploy_keys_absent(parsed: dict[str, str]) -> None:
    for key in parsed:
        assert not key.startswith("TARGET_"), key
        assert not key.startswith("SSH_"), key
        assert not key.startswith("SKIP_"), key
    for key in ABSENT_EXACT:
        assert key not in parsed


def test_runtime_env_defaults_omit_deploy_keys() -> None:
    stdout, parsed = run_filter({**REQUIRED, **DEPLOY_ONLY})
    assert stdout.splitlines()[0] == HEADER
    assert parsed == {
        "OPENROUTER_API_KEY": "test-openrouter",
        "TELEGRAM_BOT_TOKEN": "test-telegram",
        "TELEGRAM_ALLOWED_USERS": "1",
        "FIRECRAWL_API_URL": "http://127.0.0.1:3002",
        "SEARXNG_URL": "http://127.0.0.1:8888",
        "HERMES_TELEGRAM_DISABLE_FALLBACK_IPS": "true",
        "TIMEZONE": "Asia/Dubai",
        "TZ": "Asia/Dubai",
    }
    assert_deploy_keys_absent(parsed)


def test_discord_half_pair_omits_discord_keys() -> None:
    only_token = {
        **REQUIRED,
        "DISCORD_BOT_TOKEN": "tok",
        "DISCORD_HOME_CHANNEL": "123",
    }
    _, parsed = run_filter(only_token)
    assert not any(key.startswith("DISCORD_") for key in parsed)

    only_users = {
        **REQUIRED,
        "DISCORD_ALLOWED_USERS": "42",
        "DISCORD_HOME_CHANNEL": "123",
    }
    _, parsed = run_filter(only_users)
    assert not any(key.startswith("DISCORD_") for key in parsed)


def test_discord_both_copies_allow_all_only_when_set() -> None:
    base = {
        **REQUIRED,
        "DISCORD_BOT_TOKEN": "tok",
        "DISCORD_ALLOWED_USERS": "42",
    }
    _, parsed = run_filter(base)
    assert parsed["DISCORD_BOT_TOKEN"] == "tok"
    assert parsed["DISCORD_ALLOWED_USERS"] == "42"
    assert "DISCORD_ALLOW_ALL_USERS" not in parsed

    _, parsed = run_filter({**base, "DISCORD_ALLOW_ALL_USERS": "true"})
    assert parsed["DISCORD_ALLOW_ALL_USERS"] == "true"


def test_notion_half_pair_omits_notion_keys() -> None:
    only_key = {
        **REQUIRED,
        "NOTION_API_KEY": "ntn_test",
        "NOTION_TOKEN": "should-not-leak",
    }
    _, parsed = run_filter(only_key)
    assert not any(key.startswith("NOTION_") for key in parsed)

    only_page = {
        **REQUIRED,
        "NOTION_REPORTS_PARENT_PAGE_ID": "page-id",
        "NOTION_TOKEN": "should-not-leak",
    }
    _, parsed = run_filter(only_page)
    assert not any(key.startswith("NOTION_") for key in parsed)


def test_notion_both_sets_token_from_api_key() -> None:
    _, parsed = run_filter(
        {
            **REQUIRED,
            "NOTION_API_KEY": "ntn_test",
            "NOTION_REPORTS_PARENT_PAGE_ID": "page-id",
        }
    )
    assert parsed["NOTION_API_KEY"] == "ntn_test"
    assert parsed["NOTION_REPORTS_PARENT_PAGE_ID"] == "page-id"
    assert parsed["NOTION_TOKEN"] == "ntn_test"


def test_aws_access_key_is_in_runtime_env() -> None:
    _, parsed = run_filter({**REQUIRED, "AWS_ACCESS_KEY_ID": "test-access-key"})
    assert parsed["AWS_ACCESS_KEY_ID"] == "test-access-key"


def test_gateway_allow_all_unset_absent_and_copied_when_set() -> None:
    _, parsed = run_filter(REQUIRED)
    assert "GATEWAY_ALLOW_ALL_USERS" not in parsed

    _, parsed = run_filter({**REQUIRED, "GATEWAY_ALLOW_ALL_USERS": "true"})
    assert parsed["GATEWAY_ALLOW_ALL_USERS"] == "true"


def test_deploy_calls_the_shared_filter_after_ssh() -> None:
    text = (ROOT / "scripts/deploy.sh").read_text()
    lib = (ROOT / "scripts/lib/runtime-env.sh").read_text()
    assert "\nbuild_runtime_env >" in text
    assert "FIRECRAWL_API_URL=" not in text
    assert "FIRECRAWL_API_URL=" in lib
    assert text.index('log "SSH probe') < text.index("build_runtime_env")
    assert 'chmod 600 "$RUNTIME_ENV"' in text
